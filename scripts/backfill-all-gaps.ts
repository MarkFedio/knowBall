// ============================================================================
// Execution Pipeline
// ============================================================================
async function run() {
  console.log('======================================================');
  console.log('   SYSTEMIC DATA REMEDIATION & GAP CLOSURE PIPELINE');
  console.log('======================================================\n');

  // --- 1. NFL INGESTION & JERSEY BACKFILL ---
  console.log('--- Step 1: Processing NFL Database ---');
  const nflRaw = fs.readFileSync(NFL_FILE, 'utf-8');
  const nflAthletes: Athlete[] = JSON.parse(nflRaw);
  console.log(`Original NFL athlete count: ${nflAthletes.length}`);

  const nflRostersRaw = fs.existsSync(NFL_ROSTERS_FILE) ? fs.readFileSync(NFL_ROSTERS_FILE, 'utf-8') : '{}';
  const nflRosters: Record<string, any> = JSON.parse(nflRostersRaw);

  const nflNameMap = new Map<string, Athlete>();
  for (const a of nflAthletes) {
    nflNameMap.set(a.name.toLowerCase().trim(), a);
  }

  // 1a. Backfill jersey numbers for existing post-1970 HOF athletes
  let jerseysUpdatedCount = 0;
  for (const a of nflAthletes) {
    const key = a.name.toLowerCase().trim();
    const numbers = NFL_HOF_JERSEYS[key];
    if (numbers && numbers.length > 0) {
      if (!a.jerseyNumbers) a.jerseyNumbers = [];
      let changed = false;
      for (const num of numbers) {
        if (!a.jerseyNumbers.includes(num)) {
          a.jerseyNumbers.push(num);
          changed = true;
        }
      }
      if (changed) jerseysUpdatedCount++;
    }

    // 1b. Fix truncated activeYears using aggregated historical rosters
    const rData = nflRosters[key];
    if (rData && rData.years && rData.years.length > 0) {
      const minYear = Math.min(...rData.years);
      if (minYear < a.activeYears[0]) {
        a.activeYears[0] = minYear;
      }
    }
  }
  console.log(`Updated jersey numbers for ${jerseysUpdatedCount} NFL Hall of Famers.`);

  // 1c. Ingest missing pre-1970 NFL legends
  let legendsAdded = 0;
  const pre1970ConfigMap = new Map<string, Pre1970LegendConfig>();
  for (const leg of PRE_1970_NFL_LEGENDS) {
    pre1970ConfigMap.set(leg.name.toLowerCase().trim(), leg);
  }

  // Also dynamically parse Table 1 from wiki_hof.json
  const wikiRaw = fs.readFileSync(WIKI_NFL_HOF, 'utf-8');
  const wikiData = JSON.parse(wikiRaw);
  const wikitext = wikiData.parse?.wikitext?.['*'] || '';
  const table1Text = wikitext.substring(10643, 134517);
  const chunks = table1Text.split(/\|\-style="border-top: 2px solid gray"/).slice(1);

  const nicknameMap: Record<string, string> = {
    'john "paddy" driscoll': 'paddy driscoll',
    'albert glen "turk" edwards': 'turk edwards',
    'harold "red" grange': 'red grange',
    'elroy (crazylegs) hirsch': 'crazy legs hirsch',
    'frank "bruiser" kinard': 'bruiser kinard',
    'earl "curly" lambeau': 'curly lambeau',
    'dick "night train" lane': 'night train lane',
    'alphonse "tuffy" leemans': 'tuffy leemans',
    'william r. lyman': 'roy lyman',
    'anthony muñoz': 'anthony munoz',
    'o. j. simpson': 'o.j. simpson',
    'y. a. tittle': 'y.a. tittle',
  };

  for (const chunk of chunks) {
    const sortMatch = chunk.match(/\{\{sortname\s*\|\s*([^\|\}]+)\s*\|\s*([^\|\}]+)(?:\|[^\}]+)?\}\}/i);
    if (!sortMatch) continue;
    const first = sortMatch[1].trim();
    const last = sortMatch[2].trim();
    const rawName = `${first} ${last}`.replace(/\s+/g, ' ');

    const posMatch = chunk.match(/data-sort-value="([^"]+)"/i);
    const posVal = posMatch ? posMatch[1].toLowerCase() : '';

    const isNonPlayer =
      (posVal.includes('coach') ||
        posVal.includes('contributor') ||
        posVal.includes('general manager') ||
        posVal.includes('executive') ||
        posVal.includes('founder') ||
        posVal.includes('owner') ||
        posVal.includes('referee') ||
        posVal.includes('commissioner')) &&
      !(
        posVal.includes('back') ||
        posVal.includes('end') ||
        posVal.includes('tackle') ||
        posVal.includes('guard') ||
        posVal.includes('center') ||
        posVal.includes('safety') ||
        posVal.includes('cornerback') ||
        posVal.includes('quarterback') ||
        posVal.includes('kicker') ||
        posVal.includes('punter')
      );

    if (isNonPlayer) continue;

    const lookupName = nicknameMap[rawName.toLowerCase()] || rawName.toLowerCase();
    const existing = nflNameMap.get(rawName.toLowerCase()) || nflNameMap.get(lookupName);

    if (existing) {
      existing.hallOfFame = true;
      continue;
    }

    // Check if we have curated PRE_1970 config
    const curated = pre1970ConfigMap.get(rawName.toLowerCase()) || pre1970ConfigMap.get(lookupName);
    if (curated) {
      const idSafe = curated.name.toLowerCase().replace(/[^a-z0-9]/g, '_');
      const newAthlete: Athlete = {
        id: `ath_nfl_hof_${idSafe}`,
        name: curated.name,
        sports: ['NFL'],
        teams: [...curated.teams],
        teamNames: [...curated.teamNames],
        markets: [...curated.markets],
        positions: [...curated.positions],
        activeYears: [curated.activeYears[0], curated.activeYears[1]],
        jerseyNumbers: [...curated.jerseys],
        championships: curated.championships,
        mvps: curated.mvps,
        hallOfFame: true,
        rookieOfTheYear: false,
        stats: { points: 100, turnovers: 10 },
        popularityScore: curated.popularityScore,
        championshipMarkets: [...curated.championshipMarkets],
        mvpMarkets: [...curated.mvpMarkets],
      };
      nflAthletes.push(newAthlete);
      nflNameMap.set(curated.name.toLowerCase().trim(), newAthlete);
      legendsAdded++;
    } else {
      // Ingest dynamically from historical rosters
      const rData = nflRosters[lookupName] || nflRosters[rawName.toLowerCase()];
      if (rData && rData.teams && rData.teams.length > 0) {
        const teams = Array.from(new Set(rData.teams as string[]));
        const teamNames = Array.from(new Set(rData.teamNames as string[]));
        const markets = Array.from(
          new Set(teams.map((t) => MASTER_TEAM_TO_MARKET[t] || MASTER_TEAM_TO_MARKET[t.toUpperCase()]).filter(Boolean))
        );
        const minYear = Math.min(...(rData.years as number[]));
        const maxYear = Math.max(...(rData.years as number[]));

        const idSafe = rawName.toLowerCase().replace(/[^a-z0-9]/g, '_');
        const newAthlete: Athlete = {
          id: `ath_nfl_hof_${idSafe}`,
          name: rawName,
          sports: ['NFL'],
          teams,
          teamNames,
          markets,
          positions: ['ATH'],
          activeYears: [minYear, maxYear],
          jerseyNumbers: rData.jerseys && rData.jerseys.length > 0 ? rData.jerseys : [1],
          championships: rData.championships || 0,
          mvps: 0,
          hallOfFame: true,
          rookieOfTheYear: false,
          stats: { points: 100, turnovers: 10 },
          popularityScore: 85,
          championshipMarkets: rData.championships > 0 && markets.length > 0 ? [markets[0]] : [],
          mvpMarkets: [],
        };
        nflAthletes.push(newAthlete);
        nflNameMap.set(rawName.toLowerCase().trim(), newAthlete);
        legendsAdded++;
      }
    }
  }

  // Ensure every championship / MVP athlete has corresponding championshipMarkets and mvpMarkets
  for (const a of nflAthletes) {
    if (a.championships > 0 && (!a.championshipMarkets || a.championshipMarkets.length === 0)) {
      a.championshipMarkets = a.markets && a.markets.length > 0 ? [a.markets[0]] : ['NY'];
    }
    if (a.mvps > 0 && (!a.mvpMarkets || a.mvpMarkets.length === 0)) {
      a.mvpMarkets = a.markets && a.markets.length > 0 ? [a.markets[0]] : ['NY'];
    }
  }

  console.log(`Added ${legendsAdded} missing historic NFL Hall of Fame legends.`);
  fs.writeFileSync(NFL_FILE, JSON.stringify(nflAthletes, null, 2), 'utf-8');
  console.log(`Saved ${nflAthletes.length} total athletes to ${NFL_FILE}`);

  // --- 2. NHL HOF SYNCHRONIZATION & PROSPECT PURGE ---
  console.log('\n--- Step 2: Processing NHL Database ---');
  const nhlRaw = fs.readFileSync(NHL_FILE, 'utf-8');
  const nhlAthletes: Athlete[] = JSON.parse(nhlRaw);
  console.log(`Original NHL athlete count: ${nhlAthletes.length}`);

  let nhlHofFixed = 0;
  for (const a of nhlAthletes) {
    if (NHL_HOF_STATUS_FIXES[a.id] !== undefined) {
      if (!a.hallOfFame) {
        a.hallOfFame = true;
        nhlHofFixed++;
      }
    }
    // Safeguard championshipMarkets & mvpMarkets
    if (a.championships > 0 && (!a.championshipMarkets || a.championshipMarkets.length === 0)) {
      a.championshipMarkets = a.markets && a.markets.length > 0 ? [a.markets[0]] : ['MTL'];
    }
    if (a.mvps > 0 && (!a.mvpMarkets || a.mvpMarkets.length === 0)) {
      a.mvpMarkets = a.markets && a.markets.length > 0 ? [a.markets[0]] : ['MTL'];
    }
  }
  console.log(`Synchronized hallOfFame=true for ${nhlHofFixed} historic NHL legends.`);

  // Purge 0-game prospects from NHL
  const validNhl = nhlAthletes.filter((a) => {
    const hasTeams = a.teams && a.teams.length > 0;
    const hasMarkets = a.markets && a.markets.length > 0;
    const hasYears = a.activeYears && !(a.activeYears[0] === 0 && a.activeYears[1] === 0);
    return hasTeams && hasMarkets && hasYears;
  });
  const nhlPurgedCount = nhlAthletes.length - validNhl.length;
  console.log(`Purged ${nhlPurgedCount} ineligible 0-game prospects from NHL.`);
  fs.writeFileSync(NHL_FILE, JSON.stringify(validNhl, null, 2), 'utf-8');
  console.log(`Saved ${validNhl.length} valid athletes to ${NHL_FILE}`);

  // --- 3. MLB PROSPECT PURGE ---
  console.log('\n--- Step 3: Processing MLB Database ---');
  const mlbRaw = fs.readFileSync(MLB_FILE, 'utf-8');
  const mlbAthletes: Athlete[] = JSON.parse(mlbRaw);
  console.log(`Original MLB athlete count: ${mlbAthletes.length}`);

  // Purge 0-game prospects from MLB
  const validMlb = mlbAthletes.filter((a) => {
    const hasTeams = a.teams && a.teams.length > 0;
    const hasMarkets = a.markets && a.markets.length > 0;
    return hasTeams && hasMarkets;
  });
  const mlbPurgedCount = mlbAthletes.length - validMlb.length;
  console.log(`Purged ${mlbPurgedCount} ineligible 0-game prospects from MLB.`);
  fs.writeFileSync(MLB_FILE, JSON.stringify(validMlb, null, 2), 'utf-8');
  console.log(`Saved ${validMlb.length} valid athletes to ${MLB_FILE}`);

  console.log('\n======================================================');
  console.log('REMEDIATION COMPLETE! Running validation checks next...');
  console.log('======================================================\n');
}

run().catch(console.error);

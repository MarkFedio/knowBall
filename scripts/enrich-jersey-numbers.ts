function enrichAthletes(filePath: string, jerseysMap: Record<string, number[]>, sportName: string) {
  console.log(`Enriching ${sportName} athletes from ${filePath}...`);
  const raw = fs.readFileSync(filePath, 'utf-8');
  const athletes: Athlete[] = JSON.parse(raw);

  let updatedCount = 0;
  for (const a of athletes) {
    const key = a.name.toLowerCase().trim();
    const numbers = jerseysMap[key];
    if (numbers && numbers.length > 0) {
      if (!a.jerseyNumbers) a.jerseyNumbers = [];
      let added = false;
      for (const num of numbers) {
        if (!a.jerseyNumbers.includes(num)) {
          a.jerseyNumbers.push(num);
          added = true;
        }
      }
      if (added) updatedCount++;
    }
  }

  console.log(`Updated ${updatedCount} ${sportName} athletes with jersey numbers.`);
  fs.writeFileSync(filePath, JSON.stringify(athletes, null, 2), 'utf-8');
}

